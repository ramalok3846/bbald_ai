const STOP = /^(그리고|그런데|근데|이거|저거|그거|뭐|뭔가|좀|진짜|너무|아주|정말|한번|해줘|알려줘|말해줘|있어|없어|있는|하는|이랑|같이|그냥|혹시|어떻게|왜|무슨|어떤)$/;

// 질문에서 핵심 낱말(가장 긴 한글/영문 덩어리) 하나를 뽑는다.
export function extractTopic(text) {
  const words = (text.match(/[가-힣A-Za-z0-9]{2,}/g) || [])
    .map((w) => w.replace(/(이|가|은|는|을|를|의|에|에서|으로|로|랑|이랑|도|만|까지|부터|한테|께)$/, ""))
    .filter((w) => w.length >= 2 && !STOP.test(w));
  words.sort((a, b) => b.length - a.length);
  return words[0] || "";
}

function dynamicAnswer(kind, now, rand) {
  const t = kstDate(now);
  if (kind === "time") {
    const ap = t.h < 12 ? "오전" : "오후";
    const h12 = t.h % 12 === 0 ? 12 : t.h % 12;
    return pick([`지금은 ${ap} ${h12}시 ${t.min}분이다능! ⏰ (한국 시간)`, `빨드 시계로는 ${ap} ${h12}시 ${t.min}분이다능! 맞겠지...? 🦕`], rand);
  }
  if (kind === "date") return `오늘은 ${t.y}년 ${t.m}월 ${t.d}일 ${DAYS[t.dow]}요일이다능! 📅`;
  if (kind === "dow") return `오늘은 ${DAYS[t.dow]}요일이다능! ${t.dow === 0 || t.dow === 6 ? "주말이라 좋다능~" : "오늘도 화이팅이다능!"}`;
  return null;
}

// history: [{role, content}] — 이름 기억, 직전 답변 반복 방지, 이어지는 대화에 사용.
export function brainReply(userText, { history = [], rand = Math.random, now = new Date() } = {}) {
  const text = String(userText || "").trim();
  const lastBot = [...history].reverse().find((h) => h.role === "assistant")?.content || "";

  // 1) 이름 기억 / 회상
  const tell = text.match(/(?:내|제|나의)\s*이름(?:은|이)?\s*([가-힣A-Za-z]{1,10}?)(?:이야|이에요|예요|입니다|이다|야|다)?(?=[\s.!~?]|$)/);
  if (tell && !/뭐|뭘|뭐게|알아/.test(text)) {
    return `${tell[1]}! 이름 예쁘다능~ 빨드가 기억해둘게다능 🦕`;
  }
  if (/(내|제)\s*이름.*(뭐|알아|기억)/.test(text)) {
    for (const h of [...history].reverse()) {
      if (h.role !== "user") continue;
      const m = h.content.match(/(?:내|제|나의)\s*이름(?:은|이)?\s*([가-힣A-Za-z]{1,10}?)(?:이야|이에요|예요|입니다|이다|야|다)?(?=[\s.!~?]|$)/);
      if (m) return `${m[1]}! 맞지?? 빨드 기억력 좋다능 으쓱 🦕`;
    }
    return "음... 아직 이름 안 알려줬다능! '내 이름은 OO야' 하고 알려주면 기억할게다능!";
  }

  // 2) 지식 사전
  for (const k of KNOWLEDGE) {
    if (!k.re.test(text)) continue;
    if (k.dyn) {
      const r = dynamicAnswer(k.dyn, now, rand);
      if (r) return r;
    }
    return pick(k.a, rand, lastBot);
  }

  // 3) 못 알아들음: 질문이면 핵심 낱말을 되받고, 아니면 맞장구
  const topic = extractTopic(text);
  const isQuestion = /[?？]|(뭐|왜|어떻게|언제|어디|누구|얼마|무슨|어떤|알려|가르쳐)/.test(text);
  if (isQuestion) {
    if (topic) return pick(FALLBACK_Q, rand, lastBot).replace("{t}", topic);
    return pick(FALLBACK_Q_NO_TOPIC, rand, lastBot);
  }
  if (topic && rand() < 0.5) return `'${topic}' 이야기다능! ${pick(FALLBACK_CHAT, rand, lastBot)}`;
  return pick(FALLBACK_CHAT, rand, lastBot);
}
