function kstDate(now) {
  const k = new Date(now.getTime() + 9 * 3600 * 1000);
  return { y: k.getUTCFullYear(), m: k.getUTCMonth() + 1, d: k.getUTCDate(), dow: k.getUTCDay(), h: k.getUTCHours(), min: k.getUTCMinutes() };
}

